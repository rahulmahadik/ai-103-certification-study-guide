function copyLicences() {
  const out = join(ROOT, 'THIRD-PARTY-NOTICES.md');
  const parts = [
    '# Third-party notices',
    '',
    'This repository redistributes the following third-party assets. Each is',
    'used under the licence shown, and each licence text is reproduced in full',
    'below. Where a package declares a licence but ships no text, the canonical',
    'text for that licence is reproduced instead.',
    '',
    '| Asset | Package | Licence |',
    '| --- | --- | --- |',
    '| Fluent UI System Icons | `@fluentui/svg-icons` | MIT |',
    '| Inter | `@fontsource/inter` | SIL Open Font License 1.1 |',
    '| Barlow Condensed | `@fontsource/barlow-condensed` | SIL Open Font License 1.1 |',
    '| JetBrains Mono | `@fontsource/jetbrains-mono` | SIL Open Font License 1.1 |',
    '',
  ];

  const sources = [
    ['Fluent UI System Icons (MIT)', join(MODULES, '@fluentui', 'svg-icons', 'LICENSE'),
     mitText('Microsoft Corporation')],
    ['Inter (SIL OFL 1.1)', join(MODULES, '@fontsource', 'inter', 'LICENSE')],
    ['Barlow Condensed (SIL OFL 1.1)', join(MODULES, '@fontsource', 'barlow-condensed', 'LICENSE')],
    ['JetBrains Mono (SIL OFL 1.1)', join(MODULES, '@fontsource', 'jetbrains-mono', 'LICENSE')],
  ];

  // These assets are redistributed, so their licence text has to ship. A
  // missing one used to be skipped silently, which produced a notices file
  // that claimed MIT for the Fluent icons without carrying the text —
  // @fluentui/svg-icons declares MIT in package.json but ships no LICENSE
  // file. Now it falls back to the canonical text, and a genuinely missing
  // licence fails the build.
  let missing = 0;
  for (const [title, path, fallback] of sources) {
    const text = existsSync(path) ? readFileSync(path, 'utf8').trim() : fallback;
    if (!text) {
      console.error(`  no licence text for ${title} — it is redistributed, so this cannot ship`);
      missing++;
      continue;
    }
    parts.push(`## ${title}`, '', '```text', text, '```', '');
  }

  if (missing) process.exit(1);

  writeFileSync(out, parts.join('\n'));
  console.log(`licences: ${sources.length} texts -> THIRD-PARTY-NOTICES.md`);
}

