/**
 * Fluent ships each icon as a standalone <svg>. Lift the inner markup and the
 * viewBox into a <symbol> so the whole set costs one inline sprite and each
 * use site is a four-attribute <use>.
 */
function toSymbol(id, name) {
  const file = join(MODULES, '@fluentui', 'svg-icons', 'icons', `${name}.svg`);

  if (!existsSync(file)) {
    throw new Error(`icon "${name}" not found — check the name in ICONS`);
  }

  const svg = readFileSync(file, 'utf8');
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 24 24';
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*fill="[^"]*"/g, '')
    .trim();

  return `<symbol id="i-${id}" viewBox="${viewBox}">${inner}</symbol>`;
}

function buildIcons() {
  const symbols = Object.entries(ICONS).map(([id, name]) => toSymbol(id, name));

  const sprite =
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n` +
    `<!-- Microsoft Fluent UI System Icons, MIT licensed.\n` +
    `     Generated by tools/build-assets.mjs — do not edit by hand. -->\n` +
    symbols.join('\n') + `\n</svg>\n`;

  writeFileSync(join(ASSETS, 'icons.svg'), sprite);
  console.log(`icons: ${symbols.length} symbols -> docs/assets/icons.svg`);
}

