/**
 * build-assets.mjs — vendor the fonts and icons into docs/assets.
 *
 * Nothing on this site loads from a CDN. Fonts and icons are installed as
 * devDependencies and copied into the repo at build time, so a published page
 * is self-contained and renders identically offline, in CI, and on GitHub
 * Pages.
 *
 *   fonts  — Inter, Barlow Condensed and JetBrains Mono, all SIL Open Font
 *            License 1.1, from the @fontsource packages
 *   icons  — Microsoft's Fluent UI System Icons, MIT licensed, extracted from
 *            @fluentui/svg-icons into one inline <symbol> sprite
 *
 * Run with: npm run assets
 */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MODULES = join(ROOT, 'node_modules');
const ASSETS = join(ROOT, 'docs', 'assets');
const FONT_DIR = join(ASSETS, 'fonts');

/* ------------------------------------------------------------------ fonts */

const FONTS = [
  { pkg: 'inter', family: 'Inter', weights: [400, 500, 600, 700, 800] },
  { pkg: 'barlow-condensed', family: 'Barlow Condensed', weights: [600, 700] },
  { pkg: 'jetbrains-mono', family: 'JetBrains Mono', weights: [500, 700] },
];

function buildFonts() {
  mkdirSync(FONT_DIR, { recursive: true });
  const faces = [];

  for (const { pkg, family, weights } of FONTS) {
    for (const weight of weights) {
      const file = `${pkg}-latin-${weight}-normal.woff2`;
      const from = join(MODULES, '@fontsource', pkg, 'files', file);

      if (!existsSync(from)) {
        console.warn(`  missing font file ${file} — skipped`);
        continue;
      }

      copyFileSync(from, join(FONT_DIR, file));
      faces.push(
        `@font-face {\n` +
        `  font-family: '${family}';\n` +
        `  font-style: normal;\n` +
        `  font-weight: ${weight};\n` +
        `  font-display: block;\n` +
        `  src: url('fonts/${file}') format('woff2');\n` +
        `}`
      );
    }
  }

  const css =
    `/* Generated by tools/build-assets.mjs — do not edit by hand.\n` +
    `   Inter, Barlow Condensed and JetBrains Mono, SIL Open Font License 1.1.\n` +
    `   Self-hosted: this site loads nothing from a CDN. */\n\n` +
    faces.join('\n\n') + '\n';

  writeFileSync(join(ASSETS, 'fonts.css'), css);
  console.log(`fonts: ${faces.length} faces -> docs/assets/fonts.css`);
}

